/**
 * Regenerates lib/declared.generated.ts from the repo itself.
 *
 * The admin page's whole value is that it does not lie, so its "declared"
 * column has to come from the files that actually govern the platform rather
 * than from a list somebody typed. This reads those files at build time and
 * emits a module the app can import — because the app is deployed with
 * `apps/home` as its Vercel Root Directory, and files outside that directory
 * are present during the build but not reliably readable at runtime.
 *
 * Runs as `prebuild`, so a deploy always ships a fresh manifest. The output is
 * committed as well, so `tsc --noEmit` works on a clean checkout and so that a
 * pull request which changes an app's environment contract shows the manifest
 * changing alongside it.
 *
 * Degrades to an empty manifest rather than failing the build: the hub must
 * still deploy if it is ever built outside the monorepo.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const appsDir = join(here, "..", "..");
const repoRoot = join(appsDir, "..");
const out = join(here, "..", "lib", "declared.generated.ts");

/** Variable names only. Values are never read, so none can ever be emitted. */
function envNames(appDir) {
  const file = join(appDir, ".env.example");
  if (!existsSync(file)) return [];
  return readFileSync(file, "utf8")
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#") && line.includes("="))
    .map((line) => line.slice(0, line.indexOf("=")).trim())
    .filter(Boolean);
}

function hasRoute(appDir, route) {
  return existsSync(join(appDir, "app", "api", route, "route.ts"));
}

/**
 * Which apps CI will actually build.
 *
 * This used to parse a hardcoded `app: [a, b, c]` list, because that is what the
 * matrix was, and an app missing from it built untested without failing. The
 * workflow now derives the roster from `apps/` at run time, so there is no list
 * to read and the two can no longer disagree.
 *
 * Both shapes are handled: a literal list is still parsed where one exists, and
 * a derived roster reports the folders on disk, which is what CI will enumerate.
 * Same shape either way, so the page comparing this against `apps` is unchanged.
 */
function ciMatrix() {
  const file = join(repoRoot, ".github", "workflows", "ci.yml");
  if (!existsSync(file)) return [];
  const yml = readFileSync(file, "utf8");

  const literal = yml.match(/app:\s*\[([^\]]+)\]/);
  if (literal) return literal[1].split(",").map((s) => s.trim()).filter(Boolean);

  const derived = /matrix:\s*\n\s*app:\s*\$\{\{\s*fromJson\(/.test(yml);
  if (!derived) return [];

  try {
    return readdirSync(appsDir, { withFileTypes: true })
      .filter((e) => e.isDirectory())
      .map((e) => e.name)
      .sort();
  } catch {
    return [];
  }
}

function migrationCount() {
  const dir = join(repoRoot, "supabase", "migrations");
  if (!existsSync(dir)) return null;
  return readdirSync(dir).filter((f) => f.endsWith(".sql")).length;
}

let apps = [];
try {
  apps = readdirSync(appsDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(appsDir, e.name, "package.json")))
    .map((e) => {
      const dir = join(appsDir, e.name);
      return {
        slug: e.name,
        envNames: envNames(dir),
        hasHealthRoute: hasRoute(dir, "health"),
        hasSummaryRoute: hasRoute(dir, "summary"),
        hasTestScript: !!JSON.parse(readFileSync(join(dir, "package.json"), "utf8")).scripts?.test,
      };
    })
    .sort((a, b) => a.slug.localeCompare(b.slug));
} catch {
  apps = [];
}

const manifest = {
  generatedAt: new Date().toISOString(),
  complete: apps.length > 0,
  ciMatrix: ciMatrix(),
  migrationCount: migrationCount(),
  apps,
};

writeFileSync(
  out,
  `// GENERATED by scripts/collect-declared.mjs — do not edit by hand.\n` +
    `// Regenerate with \`npm run declared\`; \`npm run build\` does it automatically.\n` +
    `// Contains variable NAMES only. No value is ever read from .env files.\n\n` +
    `import type { Declared } from "./platform";\n\n` +
    `export const DECLARED: Declared = ${JSON.stringify(manifest, null, 2)};\n`
);

console.log(
  `declared: ${apps.length} apps, ${manifest.ciMatrix.length} in CI matrix, ${manifest.migrationCount ?? "?"} migrations`
);
