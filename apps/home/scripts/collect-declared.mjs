/**
 * Regenerates lib/declared.generated.ts from the repo itself.
 *
 * Which apps expose which routes, read off the folders rather than typed. The
 * Garage probes the shared secret on every app with an `/api/summary` and names
 * every app with an `/api/health` among its blind spots, so both lists come
 * from the repo. This reads it at build time and emits a module the app can
 * import — because the app is deployed with `apps/home` as its Vercel Root
 * Directory, and files outside that directory are present during the build but
 * not reliably readable at runtime.
 *
 * Runs before every build, dev server and test run (`npm run generate`), so a
 * deploy always ships a fresh manifest. The output is gitignored: a committed
 * copy was days stale and rewritten by every local build.
 *
 * Degrades to an empty manifest rather than failing the build: home must
 * still deploy if it is ever built outside the monorepo.
 */
import { writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const appsDir = join(here, "..", "..");
const out = join(here, "..", "lib", "declared.generated.ts");

function hasRoute(appDir, route) {
  return existsSync(join(appDir, "app", "api", route, "route.ts"));
}

let apps = [];
try {
  apps = readdirSync(appsDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(appsDir, e.name, "package.json")))
    .map((e) => {
      const dir = join(appsDir, e.name);
      return {
        slug: e.name,
        hasHealthRoute: hasRoute(dir, "health"),
        hasSummaryRoute: hasRoute(dir, "summary"),
      };
    })
    .sort((a, b) => a.slug.localeCompare(b.slug));
} catch {
  apps = [];
}

const manifest = {
  generatedAt: new Date().toISOString(),
  complete: apps.length > 0,
  apps,
};

writeFileSync(
  out,
  `// GENERATED by scripts/collect-declared.mjs — do not edit by hand.\n` +
    `// Regenerate with \`npm run declared\`; \`npm run build\` does it automatically.\n\n` +
    `import type { Declared } from "./platform";\n\n` +
    `export const DECLARED: Declared = ${JSON.stringify(manifest, null, 2)};\n`
);

console.log(`declared: ${apps.length} apps`);
